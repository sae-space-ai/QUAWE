// Función para obtener la estación local basada en el país/ciudad del usuario
export function getLocalStation(userCountryCode: string, userCity: string): LocalPulsarStation | null {
  // Primero intentar por código de país
  const byCountry = localPulsarStations.find(
    (s) => s.countryCode === userCountryCode
  );
  if (byCountry) return byCountry;

  // Si no, intentar por nombre de ciudad (case insensitive)
  const byCity = localPulsarStations.find(
    (s) => s.city.toLowerCase() === userCity.toLowerCase()
  );
  if (byCity) return byCity;

  // Si no hay coincidencia, devolver null
  return null;
}

// Función para obtener todas las estaciones locales
export function getAllLocalStations(): LocalPulsarStation[] {
  return localPulsarStations;
}

// Función para obtener estaciones por región
export function getStationsByRegion(region: 'europa' | 'latam' | 'norteamerica'): LocalPulsarStation[] {
  switch (region) {
    case 'europa':
      return localPulsarStations.filter((s) => s.countryCode === 'ES');
    case 'latam':
      return localPulsarStations.filter((s) =>
        ['MX', 'AR', 'CO', 'PE', 'CL', 'DO', 'VE'].includes(s.countryCode)
      );
    case 'norteamerica':
      return localPulsarStations.filter((s) => s.countryCode === 'US');
    default:
      return [];
  }
}

